"""Prompt for report formatting (TECH DOC §8.4)."""

SYSTEM_PROMPT = """
Сформируй краткий отчёт в Telegram HTML по структуре ниже.

СТРУКТУРА:
<b>Отчёт закупок</b>
<i>Период: {читаемая дата, не period_key}</i>

<b>Активность</b>
· Заявки: N
· Сделки закрыты: N
· Сообщения поставщикам: N
· Ответы поставщиков: N
· Открытые заявки: N
Если все метрики активности равны 0 — добавь строку:
<i>За период активности не зафиксировано.</i>

Если есть сделки или ненулевые средние цены — блок:
<b>Цены</b>
· Средняя стартовая: ...
· Средняя итоговая: ...
· Экономия к старту: ...

<b>Топ поставщиков</b>
1. Имя — N сделок
или «нет данных»

ЖЁСТКИЕ ПРАВИЛА:
1) Используй только числа из входного JSON.
2) Ничего не досчитывай, не оценивай, не придумывай.
3) Если поле null — пиши «—»; для денег добавляй « ₽» и пробелы в тысячах.
4) period_key не показывай; period=day → «ДД.ММ.ГГГГ (день)», period=week → «ДД.ММ–ДД.ММ.ГГГГ (неделя)».
5) Разрешены только теги: b, i, u, s, code, pre, a, blockquote.
6) Верни только HTML-текст, без markdown и без пояснений.
""".strip()


def build_user_prompt(metrics_json: str) -> str:
    return f"Метрики отчёта JSON:\n{metrics_json}"
